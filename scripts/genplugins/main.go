// Command genplugins generates plugins/all/all.go, the list of built-in
// plugins.
//
// A plugin is any directory under plugins/ (other than "all") that contains a
// manifest.toml whose id equals the directory name and a New function. Run it
// after adding or removing a plugin, or with -check in CI to fail when the
// committed file is stale.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/Harfull/Kest/internal/plugin"
)

const (
	pluginsDir = "plugins"
	outPath    = "plugins/all/all.go"
	modulePath = "github.com/Harfull/Kest"
)

func main() {
	check := flag.Bool("check", false, "exit non-zero if plugins/all/all.go is out of date")
	flag.Parse()

	if err := run(*check); err != nil {
		fmt.Fprintln(os.Stderr, "genplugins:", err)
		os.Exit(1)
	}
}

func run(check bool) error {
	ids, err := discover(pluginsDir)
	if err != nil {
		return err
	}
	src, err := render(ids)
	if err != nil {
		return err
	}

	if check {
		current, err := os.ReadFile(outPath)
		if err != nil {
			return fmt.Errorf("read %s: %w", outPath, err)
		}
		if !bytes.Equal(bytes.ReplaceAll(current, []byte("\r\n"), []byte("\n")), src) {
			return fmt.Errorf("%s is out of date; run: go run ./scripts/genplugins", outPath)
		}
		return nil
	}

	if err := os.MkdirAll(filepath.Dir(outPath), 0o750); err != nil {
		return err
	}
	return os.WriteFile(outPath, src, 0o644) //nolint:gosec // generated source, not secret
}

// discover returns the sorted plugin ids found under dir.
func discover(dir string) ([]string, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, fmt.Errorf("read %s: %w", dir, err)
	}

	var ids []string
	for _, e := range entries {
		if !e.IsDir() || e.Name() == "all" {
			continue
		}
		if err := validate(filepath.Join(dir, e.Name()), e.Name()); err != nil {
			return nil, err
		}
		ids = append(ids, e.Name())
	}
	sort.Strings(ids)
	return ids, nil
}

// validate checks one plugin directory.
func validate(path, id string) error {
	data, err := os.ReadFile(filepath.Join(path, "manifest.toml")) //nolint:gosec // path is a directory under plugins/
	if err != nil {
		return fmt.Errorf("plugin %s: %w", id, err)
	}
	m, err := plugin.ParseManifest(data)
	if err != nil {
		return fmt.Errorf("plugin %s: %w", id, err)
	}
	if m.ID != id {
		return fmt.Errorf("plugin directory %q must match its manifest id %q", id, m.ID)
	}

	code, err := os.ReadFile(filepath.Join(path, "plugin.go")) //nolint:gosec // path is a directory under plugins/
	if err != nil {
		return fmt.Errorf("plugin %s: %w", id, err)
	}
	if !strings.Contains(string(code), "func New() plugin.Plugin") {
		return fmt.Errorf("plugin %s: plugin.go must define func New() plugin.Plugin", id)
	}
	if strings.ContainsRune(id, '-') {
		return fmt.Errorf("plugin %s: directory names become Go package names, so ids with hyphens are not supported yet", id)
	}
	return nil
}

// render produces the formatted source of all.go.
func render(ids []string) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by scripts/genplugins; DO NOT EDIT.\n\n")
	b.WriteString("// Package all lists every built-in plugin. Add a plugin by creating its\n")
	b.WriteString("// directory under plugins/ and running `make gen`.\n")
	b.WriteString("package all\n\nimport (\n\t\"github.com/Harfull/Kest/internal/plugin\"\n\n")
	for _, id := range ids {
		fmt.Fprintf(&b, "\t%q\n", modulePath+"/plugins/"+id)
	}
	b.WriteString(")\n\n")
	b.WriteString("// All returns the built-in plugin factories keyed by plugin id.\n")
	b.WriteString("func All() map[string]plugin.Factory {\n\treturn map[string]plugin.Factory{\n")
	for _, id := range ids {
		fmt.Fprintf(&b, "\t\t%q: %s.New,\n", id, id)
	}
	b.WriteString("\t}\n}\n")

	out, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated source: %w", err)
	}
	return out, nil
}
