package main

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

const goodManifest = `id = "%s"
name = "X"
version = "1"
description = "x"
`

func writePlugin(t *testing.T, root, dir, manifest, code string) {
	t.Helper()
	p := filepath.Join(root, dir)
	if err := os.MkdirAll(p, 0o750); err != nil {
		t.Fatal(err)
	}
	if manifest != "" {
		if err := os.WriteFile(filepath.Join(p, "manifest.toml"), []byte(manifest), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	if code != "" {
		if err := os.WriteFile(filepath.Join(p, "plugin.go"), []byte(code), 0o600); err != nil {
			t.Fatal(err)
		}
	}
}

const goodCode = "package x\nfunc New() plugin.Plugin { return nil }\n"

func TestDiscover(t *testing.T) {
	root := t.TempDir()
	writePlugin(t, root, "zeta", strings.Replace(goodManifest, "%s", "zeta", 1), goodCode)
	writePlugin(t, root, "alpha", strings.Replace(goodManifest, "%s", "alpha", 1), goodCode)
	writePlugin(t, root, "all", "", "") // the generated package is skipped
	if err := os.WriteFile(filepath.Join(root, "README.md"), []byte("x"), 0o600); err != nil {
		t.Fatal(err)
	}

	ids, err := discover(root)
	if err != nil {
		t.Fatalf("discover() error = %v", err)
	}
	if strings.Join(ids, ",") != "alpha,zeta" {
		t.Errorf("ids = %v", ids)
	}
}

func TestDiscoverRejectsBadPlugins(t *testing.T) {
	tests := []struct {
		name     string
		dir      string
		manifest string
		code     string
	}{
		{"no manifest", "p", "", goodCode},
		{"invalid manifest", "p", "id = ", goodCode},
		{"id differs from directory", "p", strings.Replace(goodManifest, "%s", "other", 1), goodCode},
		{"no plugin.go", "p", strings.Replace(goodManifest, "%s", "p", 1), ""},
		{"no New function", "p", strings.Replace(goodManifest, "%s", "p", 1), "package x\n"},
		{"hyphenated id", "my-plugin", strings.Replace(goodManifest, "%s", "my-plugin", 1), goodCode},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			root := t.TempDir()
			writePlugin(t, root, tt.dir, tt.manifest, tt.code)
			if _, err := discover(root); err == nil {
				t.Error("discover() succeeded, want error")
			}
		})
	}
}

func TestRender(t *testing.T) {
	src, err := render([]string{"reminders", "tasks"})
	if err != nil {
		t.Fatalf("render() error = %v", err)
	}
	got := string(src)
	for _, want := range []string{
		"// Code generated by scripts/genplugins; DO NOT EDIT.",
		"package all",
		`"github.com/Harfull/Kest/plugins/reminders"`,
		`"reminders": reminders.New,`,
		`"tasks":     tasks.New,`,
	} {
		if !strings.Contains(got, want) {
			t.Errorf("generated source missing %q:\n%s", want, got)
		}
	}
}
