// Command sync-egg generates deploy/pterodactyl/egg-kest.json.
//
// The egg's variables and settings are defined here; the installation script
// is read from deploy/pterodactyl/install.sh. Run it after changing either, or
// with -check in CI to fail when the committed egg is stale.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
)

const (
	installPath = "deploy/pterodactyl/install.sh"
	eggPath     = "deploy/pterodactyl/egg-kest.json"
)

type egg struct {
	Comment      string            `json:"_comment"`
	Meta         meta              `json:"meta"`
	ExportedAt   string            `json:"exported_at"`
	Name         string            `json:"name"`
	Author       string            `json:"author"`
	Description  string            `json:"description"`
	Features     []string          `json:"features"`
	DockerImages map[string]string `json:"docker_images"`
	FileDenylist []string          `json:"file_denylist"`
	Startup      string            `json:"startup"`
	Config       config            `json:"config"`
	Scripts      scripts           `json:"scripts"`
	Variables    []variable        `json:"variables"`
}

type meta struct {
	Version   string  `json:"version"`
	UpdateURL *string `json:"update_url"`
}

// config values are JSON documents encoded as strings, as the panel expects.
type config struct {
	Files   string `json:"files"`
	Startup string `json:"startup"`
	Logs    string `json:"logs"`
	Stop    string `json:"stop"`
}

type scripts struct {
	Installation installation `json:"installation"`
}

type installation struct {
	Script     string `json:"script"`
	Container  string `json:"container"`
	Entrypoint string `json:"entrypoint"`
}

type variable struct {
	Name         string `json:"name"`
	Description  string `json:"description"`
	EnvVariable  string `json:"env_variable"`
	DefaultValue string `json:"default_value"`
	UserViewable bool   `json:"user_viewable"`
	UserEditable bool   `json:"user_editable"`
	Rules        string `json:"rules"`
	FieldType    string `json:"field_type"`
}

func main() {
	check := flag.Bool("check", false, "exit non-zero if the committed egg differs from the generated one")
	flag.Parse()

	if err := run(*check); err != nil {
		fmt.Fprintln(os.Stderr, "sync-egg:", err)
		os.Exit(1)
	}
}

func run(check bool) error {
	script, err := os.ReadFile(installPath)
	if err != nil {
		return fmt.Errorf("read install script: %w", err)
	}

	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "    ")
	if err := enc.Encode(build(string(script))); err != nil {
		return fmt.Errorf("encode egg: %w", err)
	}

	if check {
		current, err := os.ReadFile(eggPath)
		if err != nil {
			return fmt.Errorf("read egg: %w", err)
		}
		if !bytes.Equal(normalize(current), normalize(buf.Bytes())) {
			return fmt.Errorf("%s is out of date; run: go run ./scripts/sync-egg", eggPath)
		}
		return nil
	}

	if err := os.MkdirAll(filepath.Dir(eggPath), 0o750); err != nil {
		return err
	}
	return os.WriteFile(eggPath, buf.Bytes(), 0o644) //nolint:gosec // the egg is a public, non-secret artifact
}

// normalize makes the comparison independent of line endings (git may convert
// them on Windows checkouts).
func normalize(b []byte) []byte {
	return bytes.ReplaceAll(b, []byte("\r\n"), []byte("\n"))
}

